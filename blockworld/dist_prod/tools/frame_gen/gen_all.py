def gen_chapter(n, title, facts):
    paras = [open_para(n, title)]
    for k, fact in enumerate(facts):
        paras.append(expand_fact(n, title, fact, k))
        if k % 2 == 0:
            other = "林可" if n != 1 else "老馆员"
            line2 = "你要的中立正在伤害眼睛。" if n != 1 else "别把导卡当成命运。"
            paras.append(dlg(n, "观", "我还在整理，只是开始知道整理的重量。", other, line2,
                "潮气把尾音粘在铁架上，久久不散。不散也好，散掉就会被黑场收走。"))
        else:
            paras.append(
                f"他暂停去泡茶。{pick(SENSORY,n,k+2)}"
                f"茶苦入口，苦意让他想起失败之日不该被平均——平均是一种温柔的删除。"
                f"删除权在Infinity，而他手里只有镊子与暂缓。暂缓能撑多久，取决于因果升级的速度。"
                f"{pick(CITY,n,k)}"
            )
    paras.extend(densify(n, title))
    paras.append(
        f"深夜复核：观把与「{title}」相关的匣页翻至纸毛边翻起。翻起是反抗的微型几何。"
        f"他想象原流灌进城市的声响——不是爆炸，是杂音复位：哭、砸、泼、失败的脚步、未经校准的爱。"
        f"杂音令人羞愧，也令人活着。{pick(INNER,n,6)}"
        f"若前提是抽帧可改写视野，则推论是权力可经由眼睛殖民。推论成立处，必须有人付代价去打断。"
        f"他尚不知代价全名，却已在债书上签字。签字用的是雾气呵上的镜片——模糊的署名。"
    )
    hook = "因果下一步会更紧：柜子、订单、传染与林可的原件都在收网。" if n < 40 else "故事停住，缺口留下，问题留给每一个还在看的人。"
    paras.append(close_para(n, title, hook))
    return paras

